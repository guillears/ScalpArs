#!/usr/bin/env python3
"""DIST_BUCKET_EXIT — EVAL (PREREG reports/DIST_BUCKET_EXIT_2026-11-21_PREREG.md). Research only, BACKTEST.
1) parity: grid cell 0 (today, today) vs DIST_THEORY_EXIT sim_BT REF — stop if < 99.9 %.
2) per r15 bucket DESIGN pick (thin-bucket rule N < 30 → today) → HOLDOUT once: bucket set vs today's one exit.
3) shuffled-bucket control (100×, r15 permuted within period), two-sided stop read, single re-tuned exit (descriptive).
→ reports/DIST_BUCKET_EXIT_2026-11-21_data/{tables.md, grid_by_bucket.csv, picks.csv, control.csv, stop_read.csv}"""
import os, sys, importlib.util
import numpy as np, pandas as pd
R = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sp = importlib.util.spec_from_file_location("DTE_EVAL", os.path.join(R, "scripts", "DIST_THEORY_EXIT_2026-11-21_eval.py"))
EV = importlib.util.module_from_spec(sp); sp.loader.exec_module(EV)
D = os.path.join(R, "reports", "DIST_BUCKET_EXIT_2026-11-21_data")
DAY = 86_400_000
EDGES = [-1e9, -15, -10, -5, 1e9]
BL = ["≤ −15", "−15 … −10", "−10 … −5", "> −5"]
MIN_DESIGN = 30
USD = EV.USD
OUT = []


def say(s=""):
    print(s); OUT.append(s)


def bucket(r15):
    return np.digitize(r15, EDGES[1:-1], right=True)   # ≤ −15 → 0 · (−15,−10] → 1 · (−10,−5] → 2 · > −5 → 3


def picks_for(b, N, des, mn=MIN_DESIGN):
    P = np.zeros(4, int)
    for k in range(4):
        m = des & (b == k)
        if m.sum() < mn:
            continue
        mu = N[m].mean(0)
        j = int(np.argmax(mu))
        P[k] = j if mu[j] > mu[0] + 1e-12 else 0
    return P


def assemble(b, M, P):
    return M[np.arange(len(b)), P[b]]


def read(v, v0, xm, xm0, m, dayn, hv, pair, sp_, v2=None, v02=None):
    d = v[m] - v0[m]
    lo, hi = EV.boot(d, dayn[m], sp_)
    hp = pd.Series(d).groupby(hv[m]).sum()
    tot = d.sum()
    ps = pd.Series(d).groupby(pair[m]).sum(); ds = pd.Series(d).groupby(dayn[m]).sum()
    dc0, dd0, wd0 = EV.risk(v0[m], xm0[m], sp_); dc, dd, wd = EV.risk(v[m], xm[m], sp_)
    return dict(N=int(m.sum()), changed=int((np.abs(d) > 1e-9).sum()), WR0=(v0[m] > 0).mean() * 100, WR=(v[m] > 0).mean() * 100,
                avg0=v0[m].mean(), avg=v[m].mean(), d=d.mean(), lo=lo, hi=hi, halves=f"{int((hp > 0).sum())}/{len(hp)}",
                halves_frac=(hp > 0).mean() if len(hp) else 0, d020=(v2[m] - v02[m]).mean() if v2 is not None else np.nan,
                pair_share=ps.max() / tot * 100 if tot > 0 else np.nan, top_pair=ps.idxmax() if tot > 0 else "",
                day_share=ds.max() / tot * 100 if tot > 0 else np.nan, dcr0=dc0, dcr=dc, dd0=dd0, dd=dd, worst0=wd0, worst=wd,
                usd=tot * USD / 100)


def main():
    os.makedirs(D, exist_ok=True)
    S = pd.read_pickle(os.path.join(R, "reports", "ENTRY_WL_2026-11-18_data", "dist.pkl"))
    F = pd.read_csv(os.path.join(R, "reports", "DIST_AFTERCRASH_2026-11-21_data", "features.csv.gz"))
    assert (S.pair.astype(str).values == F.pair.values).all() and (S.entry_ms.values == F.entry_ms.values).all()
    Z = dict(np.load(os.path.join(D, "sim_grid.npz"), allow_pickle=False))
    B = dict(np.load(os.path.join(R, "reports", "DIST_THEORY_EXIT_2026-11-21_data", "sim_BT.npz"), allow_pickle=False))
    assert (Z["ix"] == np.arange(len(S))).all()
    names = [str(x) for x in Z["names"]]
    par = (np.abs(Z["r"][:, 0] - B["r"][:, 0]) <= 0.01) & (Z["k"][:, 0] == B["k"][:, 0])
    say(f"# DIST_BUCKET_EXIT — tables (generated by scripts/DIST_BUCKET_EXIT_2026-11-21_eval.py)\n")
    say(f"PARITY grid (today, today) vs DIST_THEORY_EXIT REF: kind+gross match {par.sum()}/{len(par)} ({par.mean() * 100:.2f} %)")
    if par.mean() < 0.999:
        say("PARITY FAIL — stop"); open(os.path.join(D, "tables.md"), "w").write("\n".join(OUT)); sys.exit(1)
    slip = S.slip.values.astype(float)
    N = EV.nets(slip, Z["r"].astype(float), Z["k"], Z["f"].astype(float))
    N2 = EV.nets(slip, Z["r"].astype(float), Z["k"], Z["f"].astype(float), flat=0.20)
    ok = np.isfinite(N).all(1)
    say(f"fills with a finite net in every cell: {ok.sum()} of {len(S)} (censored dropped from every cell)")
    S = S[ok].reset_index(drop=True); F = F[ok].reset_index(drop=True)
    N, N2 = N[ok], N2[ok]
    K, XM = Z["k"][ok], Z["xm"][ok]
    T = S.entry_ms.values.astype(np.int64); dayn = T // DAY
    des = T < EV.SPAN["DESIGN"][1]; hol = ~des
    hv = EV.half_of(T); pair = S.pair.astype(str).values
    r15 = F.r15.values.astype(float); b = bucket(r15)
    say("\nbucket counts DESIGN / HOLDOUT: " + " · ".join(f"{BL[k]} {int((des & (b == k)).sum())} / {int((hol & (b == k)).sum())}" for k in range(4)))
    # ---- grid tables per bucket (DESIGN = pick basis; HOLDOUT / ALL descriptive after the read)
    rows = []
    for k in range(4):
        for per, m0 in (("DESIGN", des), ("HOLDOUT", hol), ("ALL", np.ones(len(b), bool))):
            m = m0 & (b == k)
            for j, nm in enumerate(names):
                v = N[m, j]
                rows.append(dict(bucket=BL[k], period=per, cell=nm, N=int(m.sum()), WR=(v > 0).mean() * 100 if len(v) else np.nan,
                                 avg=v.mean() if len(v) else np.nan, d_vs_today=(v - N[m, 0]).mean() if len(v) else np.nan,
                                 tp_pct=(K[m, j] == 0).mean() * 100 if len(v) else np.nan, sl_pct=(K[m, j] == 1).mean() * 100 if len(v) else np.nan))
    G = pd.DataFrame(rows); G.to_csv(os.path.join(D, "grid_by_bucket.csv"), index=False)
    tps = ["TPT", "TP5", "TP8", "TP10", "TP12", "TP15"]; sls = ["SLT", "SL4", "SL6", "SL8", "SL10"]
    for per in ("DESIGN", "HOLDOUT"):
        say(f"\n## Grid avg net %/fill — {per} (rows TP, cols SL; T = today's ATR rule)")
        for k in range(4):
            g = G[(G.bucket == BL[k]) & (G.period == per)].set_index("cell")
            say(f"\n**{BL[k]}** (N {int(g.N.iloc[0])})\n\n| TP \\ SL | " + " | ".join(sls) + " |\n|---|" + "---|" * len(sls))
            for tp in tps:
                say(f"| {tp} | " + " | ".join(f"{g.loc[f'{tp}_{sl}', 'avg']:+.2f}" for sl in sls) + " |")
    # ---- picks on DESIGN
    P = picks_for(b, N, des)
    say("\n## DESIGN picks (thin-bucket rule: DESIGN N < 30 → today's exit)")
    say("| bucket | DESIGN N | pick | DESIGN avg today | DESIGN avg pick | DESIGN Δ |")
    say("|---|---|---|---|---|---|")
    PK = []
    for k in range(4):
        m = des & (b == k)
        a0 = N[m, 0].mean(); a1 = N[m, P[k]].mean()
        note = "" if m.sum() >= MIN_DESIGN else " (thin → today)"
        say(f"| {BL[k]} | {int(m.sum())} | {names[P[k]]}{note} | {a0:+.3f} | {a1:+.3f} | {a1 - a0:+.3f} |")
        PK.append(dict(bucket=BL[k], design_N=int(m.sum()), pick=names[P[k]], design_avg_today=a0, design_avg_pick=a1))
    pd.DataFrame(PK).to_csv(os.path.join(D, "picks.csv"), index=False)
    # descriptive: in-sample all-period best for the thin buckets
    for k in (0, 1):
        g = G[(G.bucket == BL[k]) & (G.period == "ALL")].sort_values("avg", ascending=False).iloc[0]
        say(f"(descriptive, in-sample, NOT a pick) {BL[k]} all-period best cell {g.cell}: avg {g.avg:+.2f} vs today "
            f"{G[(G.bucket == BL[k]) & (G.period == 'ALL') & (G.cell == names[0])].avg.iloc[0]:+.2f}")
    # ---- HOLDOUT read
    v = assemble(b, N, P); v0 = N[:, 0]; v2 = assemble(b, N2, P); v02 = N2[:, 0]
    xm = assemble(b, XM, P); xm0 = XM[:, 0]
    say("\n## HOLDOUT read — bucket set vs today's one exit")
    say("| scope | N | changed | WR before → after | avg before → after | Δ %/fill | 95 % CI | halves > 0 | Δ @0.20 slip | top pair / day share | Δ $ (at $3,050) |")
    say("|---|---|---|---|---|---|---|---|---|---|---|")
    tot = None
    for k in list(range(4)) + ["ALL"]:
        m = hol & ((b == k) if k != "ALL" else True)
        r = read(v, v0, xm, xm0, m, dayn, hv, pair, EV.SPAN["HOLDOUT"], v2, v02)
        lbl = BL[k] if k != "ALL" else "**TOTAL**"
        say(f"| {lbl} | {r['N']} | {r['changed']} | {r['WR0']:.1f} → {r['WR']:.1f} % | {r['avg0']:+.3f} → {r['avg']:+.3f} | {r['d']:+.3f} | "
            f"[{r['lo']:+.3f}, {r['hi']:+.3f}] | {r['halves']} | {r['d020']:+.3f} | {r['pair_share']:.0f} % / {r['day_share']:.0f} % | {r['usd']:+,.0f} |")
        if k == "ALL":
            tot = r
    dd_ = pd.Series((v - v0)[hol]).groupby(hv[hol]).agg(["count", "mean"])
    say("\nHOLDOUT Δ by half (TOTAL): " + " · ".join(f"{h} N {int(r_['count'])} Δ {r_['mean']:+.3f}" for h, r_ in dd_.iterrows()))
    say(f"\nOne-size risk (0.61 × equity per fill, HOLDOUT, every calendar day): DCR {tot['dcr0']:+.3f} → {tot['dcr']:+.3f} %/day · "
        f"max DD {tot['dd0']:.1f} → {tot['dd']:.1f} % · worst day {tot['worst0']:+.2f} → {tot['worst']:+.2f} %")
    # ---- single re-tuned exit (descriptive)
    j1 = int(np.argmax(N[des].mean(0)))
    s1 = read(N[:, j1], v0, XM[:, j1], xm0, hol, dayn, hv, pair, EV.SPAN["HOLDOUT"], N2[:, j1], v02)
    say(f"\nSingle DESIGN-best exit for ALL fills (descriptive): {names[j1]} (DESIGN Δ {(N[des, j1] - N[des, 0]).mean():+.3f}) → HOLDOUT Δ "
        f"{s1['d']:+.3f} [{s1['lo']:+.3f}, {s1['hi']:+.3f}] halves {s1['halves']} @0.20 {s1['d020']:+.3f} DCR {s1['dcr0']:+.3f} → {s1['dcr']:+.3f}")
    # ---- shuffled-bucket control
    rng = np.random.default_rng(11); C = []
    for s in range(100):
        rr = r15.copy()
        for mm in (des, hol):
            idx = np.nonzero(mm)[0]; rr[idx] = rr[rng.permutation(idx)]
        bb = bucket(rr); Pp = picks_for(bb, N, des)
        vv = assemble(bb, N, Pp)
        C.append(dict(shuffle=s, hold_d=(vv[hol] - v0[hol]).mean(), picks="/".join(names[x] for x in Pp)))
    C = pd.DataFrame(C); C.to_csv(os.path.join(D, "control.csv"), index=False)
    q50, q95 = np.percentile(C.hold_d, [50, 95])
    say(f"\n## Shuffled-bucket control (100×, r15 permuted within DESIGN / HOLDOUT)")
    say(f"HOLDOUT Δ from pure fitting: median {q50:+.3f} · 95th pct {q95:+.3f} · max {C.hold_d.max():+.3f} · share of shuffles with Δ > 0: "
        f"{(C.hold_d > 0).mean() * 100:.0f} % · real {tot['d']:+.3f} → rank {(C.hold_d < tot['d']).mean() * 100:.0f} th pct")
    say("Most common shuffled pick sets: " + "; ".join(f"{p} ×{n}" for p, n in C.picks.value_counts().head(4).items()))
    # ---- sensitivity (descriptive, NOT the pre-registered read): no thin-bucket rule (every bucket fits on DESIGN, even N = 5)
    P1 = picks_for(b, N, des, mn=1); w = assemble(b, N, P1)
    rng = np.random.default_rng(12); cc = []
    for s in range(100):
        rr = r15.copy()
        for mm in (des, hol):
            idx = np.nonzero(mm)[0]; rr[idx] = rr[rng.permutation(idx)]
        bb = bucket(rr); cc.append((assemble(bb, N, picks_for(bb, N, des, mn=1))[hol] - v0[hol]).mean())
    say(f"\nSensitivity (descriptive): no thin-bucket rule → picks {' / '.join(names[x] for x in P1)} → HOLDOUT Δ total {(w[hol] - v0[hol]).mean():+.3f} "
        "(per bucket " + " · ".join(f"{BL[k]} {(w[hol & (b == k)] - v0[hol & (b == k)]).mean():+.3f}" for k in range(4)) +
        f") · its own shuffled control 95th pct {np.percentile(cc, 95):+.3f}")
    # ---- two-sided stop read (TP = today; every SL ≠ today) + the picked cells
    say("\n## Two-sided stop read (backtest, all periods; stopped = stopped under today's exit)")
    say("| bucket | cell | stopped today N | saved N · Δ $ | deeper N · Δ $ | smaller loss N · Δ $ | net on stopped $ | not-stopped: newly stopped N · Δ $ | total Δ $ |")
    say("|---|---|---|---|---|---|---|---|---|")
    SR = []
    for k in range(4):
        cand = [names.index(f"TPT_{s}") for s in ("SL4", "SL6", "SL8", "SL10")]
        if P[k] != 0 and P[k] not in cand:
            cand.append(int(P[k]))
        for j in cand:
            m = b == k; st = m & (K[:, 0] == 1); ns = m & (K[:, 0] != 1)
            d = (N[:, j] - N[:, 0]) * USD / 100
            sv = st & (K[:, j] != 1); dp = st & (K[:, j] == 1) & (d < -1e-6)
            sh = st & (K[:, j] == 1) & (d > 1e-6)
            nw = ns & (K[:, j] == 1)
            r = dict(bucket=BL[k], cell=names[j], stopped=int(st.sum()), saved_n=int(sv.sum()), saved_usd=d[sv].sum(), deeper_n=int(dp.sum()),
                     deeper_usd=d[dp].sum(), shallow_n=int(sh.sum()), shallow_usd=d[sh].sum(), stopped_net=d[st].sum(), new_stop_n=int(nw.sum()), notstopped_usd=d[ns].sum(), total=d[m].sum())
            SR.append(r)
            say(f"| {BL[k]} | {names[j]} | {r['stopped']} | {r['saved_n']} · {r['saved_usd']:+,.0f} | {r['deeper_n']} · {r['deeper_usd']:+,.0f} | {r['shallow_n']} · {r['shallow_usd']:+,.0f} | "
                f"{r['stopped_net']:+,.0f} | {r['new_stop_n']} · {r['notstopped_usd']:+,.0f} | {r['total']:+,.0f} |")
    pd.DataFrame(SR).to_csv(os.path.join(D, "stop_read.csv"), index=False)
    # ---- decision
    g = dict(ci=tot["d"] > 0 and tot["lo"] > 0, control=tot["d"] > q95, halves=tot["halves_frac"] >= 2 / 3, slip=tot["d020"] > 0,
             dcr=tot["dcr"] >= tot["dcr0"], conc=(tot["pair_share"] < 50 and tot["day_share"] < 50) if tot["d"] > 0 else False)
    say("\n## Decision gates: " + " · ".join(f"{k} {'✓' if x else '✗'}" for k, x in g.items()) + f" → {'SHIP CANDIDATE' if all(g.values()) else 'KEEP ONE EXIT'}")
    open(os.path.join(D, "tables.md"), "w").write("\n".join(OUT) + "\n")


if __name__ == "__main__":
    main()
